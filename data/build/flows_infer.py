def apply(flows):
    by = {f["id"]: f for f in flows}
    missing = []
    for f in flows:
        for b in f["bridges"]:
            if b["kind"] != "sequence":
                continue
            x = INFER.get((f["id"], b["from"]))
            if not x:
                missing.append((f["id"], b["from"]))
                continue
            b["infer"], b["inferAlt"] = x
        for l in f["links"]:
            if l["kind"] != "sequence":
                continue
            x = LINK_INFER.get((f["id"], l["from"], l["to"]))
            if not x:
                missing.append((f["id"], l["from"], l["to"]))
                continue
            l["infer"], l["inferAlt"] = x
    if missing:
        raise SystemExit(f"R-A6: 이유 추론이 없는 '시간 순서' 연결 {missing}")
    extra = [k for k in INFER if k[0] in by and not any(b["from"] == k[1] and b["kind"] == "sequence" for b in by[k[0]]["bridges"])]
    if extra:
        raise SystemExit(f"R-A6: 쓰이지 않는 추론 {extra}")


