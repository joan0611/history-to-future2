ADD_STEP = {
    "flow-jobs": [({"id": "j8b", "phase": "spread", "period": "2004", "era": "2000s", "title": "비정규직 비중 정점(2004년 37.0%)", "claimIds": ["c00-irregular"], "nodeIds": []}, "j9")],
}
STEP_CLAIMS = {("flow-jobs", "j8"): ["c90-ch-1998"]}


def apply_scope(flows, industry_ids):
    by = {f["id"]: f for f in flows}
    for fid, (tracks, q) in TRACKS.items():
        f = by[fid]
        f["tracks"] = tracks
        if q:
            f["question"] = q
    miss = [f["id"] for f in flows if not f.get("tracks")]
    if miss:
        raise SystemExit(f"R-Q3: 추적 대상이 없는 흐름 {miss}")
    for fid, adds in ADD_STEP.items():
        steps = by[fid]["steps"]
        for st, before in adds:
            if any(s["id"] == st["id"] for s in steps):
                continue
            idx = next(i for i, s in enumerate(steps) if s["id"] == before)
            steps.insert(idx, dict(st))
    for (fid, sid), cl in STEP_CLAIMS.items():
        for s in by[fid]["steps"]:
            if s["id"] == sid:
                s["claimIds"] = list(cl)
    for (fid, sid), (why, goes) in SIDE.items():
        f = by[fid]
        st = next(s for s in f["steps"] if s["id"] == sid)
        for k, t in goes:
            if k == "industry" and t not in industry_ids:
                raise SystemExit(f"R-Q5: 없는 산업 {t}")
        st["side"] = {"why": why, "go": [list(g) for g in goes]}
        f["links"] = [l for l in f["links"] if sid not in (l["from"], l["to"])]
    # 시대마다 본 흐름 단계가 하나 이상
    for f in flows:
        eras = {s["era"] for s in f["steps"] if not s.get("side")}
        lack = [e for e in f["eraStates"] if e not in eras]
        if lack:
            raise SystemExit(f"R-Q3: {f['id']} 본 흐름 단계가 없는 시대 {lack}")
