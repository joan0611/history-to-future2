def build(claims_by_id):
    out = []
    for c in CASES:
        for key, _ in LEVELS:
            items = c[key]
            lines = [x for a in items for x in (a["motive"], a["constraint"], a["alternative"])] if key == "actors" else items
            for ln in lines:
                bad = [i for i in ln["ids"] if i not in claims_by_id]
                assert not bad, (c["id"], key, bad)
                if ln["layer"] == "fact":  # 사실 줄의 숫자는 인용한 근거 문장 안에 있어야 한다
                    src = "".join(claims_by_id[i]["text"] for i in ln["ids"]).replace(",", "")
                    miss = [n for n in re.findall(r"\d+(?:\.\d+)?", ln["text"].replace(",", "")) if n not in src]
                    assert not miss, (c["id"], key, ln["text"], miss)
        out.append(c)
    return {"levels": [{"key": k, "label": l} for k, l in LEVELS], "cases": sorted(out, key=lambda c: c["year"])}
