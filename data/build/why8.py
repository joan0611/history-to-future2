def build(claims_by_id):
    out = []
    for c in CASES:
        for key, _ in LEVELS:
            items = c[key]
            lines = [x for a in items for x in (a["motive"], a["constraint"], a["alternative"])] if key == "actors" else items
            for ln in lines:
                bad = [i for i in ln["ids"] if i not in claims_by_id]
                assert not bad, (c["id"], key, bad)
        out.append(c)
    return {"levels": [{"key": k, "label": l} for k, l in LEVELS], "cases": out}
