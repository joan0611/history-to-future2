# flow-shop은 '소비·쇼핑' 5개 주제 이야기로 옮겨 갔다(주소도 그쪽으로 이동).
EXEMPT = {"flow-shop": "소비·쇼핑 5개 주제(shop-*)가 같은 대상을 전환점 이야기로 다룬다."}


def apply(flows, claims_all):
    cids = {c["id"] for c in claims_all}
    errs = []
    for f in flows:
        if f["id"] in EXEMPT:
            continue
        turns = T.get(f["id"])
        if not turns:
            errs.append(f"{f['id']}: 전환점 이야기 없음")
            continue
        for tu in turns:
            for k in ("why", "before", "condition", "response", "change", "legacy"):
                if not tu.get(k):
                    errs.append(f"{f['id']}/{tu['id']}: '{k}' 비어 있음")
            for k in ("before", "condition", "response", "change", "legacy"):
                for x in tu[k]:
                    if x["layer"] in ("fact", "source") and not x["ids"]:
                        errs.append(f"{f['id']}/{tu['id']}: 근거 없는 사실")
                    errs += [f"{f['id']}/{tu['id']}: 없는 근거 {i}" for i in x["ids"] if i not in cids]
            errs += [f"{f['id']}/{tu['id']}: 없는 근거 {i}" for i in tu["why"]["ids"] if i not in cids]
        f["turns"] = turns
    if errs:
        raise SystemExit("시대 흐름 전환점 검증 실패:\n" + "\n".join(errs))
