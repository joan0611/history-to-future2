def _am(d, a, b, ex=()):
    v = [d[y] for y in range(a, b + 1) if y not in ex]
    return sum(v) / len(v)


def _gm(d, a, b):
    p = 1.0
    for y in range(a, b + 1):
        p *= 1 + d[y] / 100
    return (p ** (1 / (b - a + 1)) - 1) * 100


