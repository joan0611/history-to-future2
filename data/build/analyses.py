def validate(claims):
    cids = {c["id"] for c in claims}
    for a in ANALYSES:
        def chk(ids, where):
            for i in ids:
                if i not in cids:
                    raise SystemExit(f"{a['id']} {where}: 없는 주장 {i}")
        sm = a["summary"]
        for y in a["findings"] + a["same"] + a["different"] + [a["whyNow"], sm["state"]] + sm["basis"] + sm["uncertain"]:
            chk(y["claimIds"], "종합")
            if not y["claimIds"]:
                raise SystemExit(f"{a['id']}: 근거 없는 종합 문장 {y['text'][:20]}")
        nodes = {n["id"] for n in a["mechanism"]["nodes"]}
        eps = {e["id"] for e in a["episodes"]}
        for e in a["mechanism"]["edges"]:
            chk(e["claimIds"], "관계도")
            if e["kind"] not in MECH_KINDS or e["from"] not in nodes or e["to"] not in nodes or not set(e["eps"]) <= eps or not e["claimIds"]:
                raise SystemExit(f"{a['id']}: 관계도 연결 오류 {e['from']}→{e['to']}")
        for r in a["rows"]:
            for k, (txt, ids) in r["cells"].items():
                chk(ids, f"비교표 {r['item']}")
                if txt and not ids:
                    raise SystemExit(f"{a['id']}: 근거 없는 비교 칸 {r['item']}/{k}")
            if any(not t for t, _ in r["cells"].values()) and not r.get("gap"):
                raise SystemExit(f"{a['id']}: 빈칸이 있는 행 '{r['item']}'에 공백 설명(gap)이 없음")
        sids = {s["id"] for s in a["scenarios"]}
        wids = set()
        for s in a["scenarios"]:
            chk(s["basis"], "시나리오")
        for w in a["watch"]:
            chk(w["claimIds"], "지표")
            wids.add(w["id"])
            for sid, _ in w["supports"] + w["weakens"]:
                if sid not in sids:
                    raise SystemExit(f"{a['id']}: 지표 {w['id']}가 없는 시나리오 {sid}를 가리킴")
        for s in a["scenarios"]:
            if not any(s["id"] == x for w in a["watch"] for x, _ in w["supports"]) or not any(s["id"] == x for w in a["watch"] for x, _ in w["weakens"]):
                raise SystemExit(f"{a['id']}: 시나리오 {s['id']}에 지지·약화 지표가 모두 연결되지 않음")
        if not set(sm["watchFirst"]) <= wids:
            raise SystemExit(f"{a['id']}: 요약의 지표 id 오류")
        # 임계값 문장 검사: 근거 없는 'n%를 넘으면' 기준을 지표 문장에 쓰지 않는다(연구 임계값은 threshold 필드로만)
        import re
        for w in a["watch"]:
            for _, t in w["supports"] + w["weakens"]:
                if re.search(r"\d+(\.\d+)?%\s*를?\s*(넘|웃돌|밑돌)", t):
                    raise SystemExit(f"{a['id']}: 지표 {w['id']} 문장에 근거 없는 수치 기준: {t}")
        a["periodTest"] = period_test(_gdp())
    return ANALYSES
