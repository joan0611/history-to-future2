def apply(seed):
    groups = [("topic", seed["topics"]["topics"]), ("industry", seed["industries"]["industries"]), ("flow", seed["flows"]["flows"]), ("taste", seed["tastes"]["flows"])]
    n, miss = 0, []
    for kind, objs in groups:
        for o in objs:
            for f in (o.get("futures") or {}).get("items", []):
                t = TERM.get((kind, o["id"], f["name"]))
                if t:
                    f["term"] = t
                    n += 1
                else:
                    miss.append(f"{kind}:{o['id']}:{f['name']}")
    seed["futureTerm"] = {"filled": n, "missing": miss}
    return seed
